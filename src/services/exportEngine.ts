/**
 * Sanitizes a mixed row of values for XLSX/CSV so strings are protected against formula injection,
 * numbers remain numbers, and null/undefined remain null (never coerced to 0).
 */
export function sanitizeExportRow(
  row: Array<string | number | boolean | null | undefined>
): Array<string | number | boolean | null> {
  return row.map((cell) => {
    if (cell === null || cell === undefined) {
      return null;
    }
    if (typeof cell === 'number') {
      return Number.isFinite(cell) ? cell : null;
    }
    if (typeof cell === 'boolean') {
      return cell;
    }
    return sanitizeSpreadsheetValue(cell);
  });
}

/**
 * 8.1 PDF Export Engine
 * Produces a real multi-page PDF document from the frozen report snapshot using jsPDF.
 */
export function generateReportPdfBytes(snapshot: FrozenReportSnapshot): Uint8Array {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const report = snapshot.reportData;
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 44;
  const contentWidth = pageWidth - margin * 2;

  // --- PAGE 1: COVER PAGE & TABLE OF CONTENTS ---
  doc.setFillColor(18, 48, 71); // Primary Navy #123047
  doc.rect(0, 0, pageWidth, 140, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('ESG ASSURANCE & AUDIT WORKBENCH v0.3.0 — INTERNAL READINESS REPORT', margin, 48);

  doc.setFontSize(18);
  const titleLines = doc.splitTextToSize(report.reportType.toUpperCase(), contentWidth);
  doc.text(titleLines, margin, 76);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(
    `Engagement: ${report.engagementId} | Period: ${report.reportingPeriod} | Version: v${report.versionNumber}`,
    margin,
    118
  );

  let y = 172;
  doc.setTextColor(28, 43, 54);

  // Mandatory Non-Opinion Assurance Disclaimer Box
  doc.setDrawColor(237, 108, 2);
  doc.setFillColor(255, 248, 238);
  doc.roundedRect(margin, y, contentWidth, 58, 4, 4, 'FD');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.setTextColor(154, 52, 18);
  doc.text('MANDATORY INTERNAL ASSURANCE-READINESS DISCLAIMER', margin + 12, y + 18);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  const discLines = doc.splitTextToSize(
    report.disclaimerStatement || MANDATORY_INTERNAL_ASSURANCE_DISCLAIMER,
    contentWidth - 24
  );
  doc.text(discLines, margin + 12, y + 34);
  y += 80;

  // Engagement & Snapshot Provenance Metadata
  doc.setTextColor(28, 43, 54);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Frozen Report Snapshot Metadata', margin, y);
  y += 18;

  const metaRows: Array<[string, string]> = [
    ['Report ID', report.reportId],
    ['Frozen Snapshot ID', snapshot.snapshotId],
    ['Engagement ID', report.engagementId],
    ['Reporting Period', report.reportingPeriod],
    ['Reporting Boundary', report.reportingBoundary],
    ['Methodology Version', report.methodologyVersion],
    ['Review Status', report.reviewStatus],
    ['Generated By', report.generatedBy],
    ['Reviewed By', report.reviewedBy ?? 'Pending Independent Review'],
    ['Generated Timestamp', report.generatedAt],
    ['Snapshot Content Hash (SHA-256)', snapshot.reportSnapshotHash],
  ];

  doc.setFontSize(9.5);
  for (const [k, v] of metaRows) {
    doc.setFont('helvetica', 'bold');
    doc.text(`${k}:`, margin, y);
    doc.setFont('helvetica', 'normal');
    const wrappedVal = doc.splitTextToSize(String(v), contentWidth - 170);
    doc.text(wrappedVal, margin + 170, y);
    y += Math.max(15, wrappedVal.length * 12);
  }

  y += 14;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Table of Contents', margin, y);
  y += 18;

  const includedSections = report.reportSections
    .filter((s) => s.included)
    .sort((a, b) => a.sectionOrder - b.sectionOrder);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  for (const sec of includedSections) {
    doc.text(`${sec.sectionTitle}`, margin + 8, y);
    y += 16;
  }

  // --- SUBSEQUENT PAGES: REPORT SECTIONS, KPIS & TABLES ---
  const ensureSpace = (neededPt: number) => {
    if (y + neededPt > pageHeight - 56) {
      doc.addPage();
      y = 52;
    }
  };

  doc.addPage();
  y = 52;

  for (const sec of includedSections) {
    ensureSpace(95);
    doc.setFillColor(240, 245, 249);
    doc.rect(margin, y - 12, contentWidth, 24, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11.5);
    doc.setTextColor(18, 48, 71);
    doc.text(sec.sectionTitle, margin + 8, y + 4);
    y += 24;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(28, 43, 54);
    const narLines = doc.splitTextToSize(sec.narrativeSummary, contentWidth);
    ensureSpace(narLines.length * 13 + 12);
    doc.text(narLines, margin, y);
    y += narLines.length * 13 + 10;

    if (sec.keyMetrics.length > 0) {
      ensureSpace(sec.keyMetrics.length * 15 + 18);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9.5);
      doc.text('Key Section Metrics:', margin, y);
      y += 14;
      doc.setFont('helvetica', 'normal');
      for (const m of sec.keyMetrics) {
        doc.text(
          `• ${m.label}: ${m.value}${m.unit ? ` (${m.unit})` : ''}`,
          margin + 10,
          y
        );
        y += 14;
      }
      y += 6;
    }

    if (sec.tableHeaders && sec.tableRows && sec.tableRows.length > 0) {
      ensureSpace(45);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8.5);
      const headerLine = sec.tableHeaders.join(' | ');
      const wrappedHead = doc.splitTextToSize(headerLine, contentWidth);
      doc.text(wrappedHead, margin, y);
      y += wrappedHead.length * 11 + 4;
      doc.setDrawColor(190, 200, 210);
      doc.line(margin, y - 4, margin + contentWidth, y - 4);

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      for (const row of sec.tableRows.slice(0, 25)) {
        const rowStr = row
          .map((cell) => (cell === null || cell === undefined ? 'NULL' : String(cell)))
          .join(' | ');
        const wrappedRow = doc.splitTextToSize(rowStr, contentWidth);
        ensureSpace(wrappedRow.length * 10 + 6);
        doc.text(wrappedRow, margin, y);
        y += wrappedRow.length * 10 + 4;
      }
      y += 10;
    }

    y += 12;
  }

  // Stamp footer page numbers and snapshot hash on every page
  const totalPages = doc.getNumberOfPages();
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(96, 112, 128);
    doc.text(
      `Snapshot: ${snapshot.snapshotId} | Hash: ${snapshot.reportSnapshotHash.slice(0, 20)}... | Generated: ${snapshot.generatedAt}`,
      margin,
      pageHeight - 24
    );
    doc.text(`Page ${p} of ${totalPages}`, pageWidth - margin - 55, pageHeight - 24);
  }

  const arrayBuffer = doc.output('arraybuffer');
  return new Uint8Array(arrayBuffer);
}

/**
 * 8.2 XLSX Export Engine
 * Produces an 8-sheet workbook from the frozen report snapshot and engagement context.
 * Sheets:
 * 1. Executive Summary
 * 2. ESG Assertions
 * 3. Control Testing
 * 4. GHG Recalculations
 * 5. Disclosure Mapping
 * 6. Evidence Register
 * 7. Findings
 * 8. Methodology
 */
export function generateReportXlsxBytes(
  snapshot: FrozenReportSnapshot,
  ctx: ReportGenerationContext
): Uint8Array {
  const wb = XLSX.utils.book_new();
  const report = snapshot.reportData;
  const engId = report.engagementId;

  const engAssertions = ctx.assertions.filter((a) => a.engagementId === engId);
  const engControls = ctx.controls.filter((c) => c.engagementId === engId);
  const ctrlIds = new Set(engControls.map((c) => c.controlId));
  const engDesign = ctx.designTests.filter((d) => ctrlIds.has(d.controlId));
  const engOperating = ctx.operatingTests.filter((o) => ctrlIds.has(o.controlId));
  const engActivities = ctx.emissionActivities.filter((a) => a.engagementId === engId);
  const actIds = new Set(engActivities.map((a) => a.activityId));
  const engRecalcs = ctx.ghgRecalculations.filter((r) => actIds.has(r.activityId));
  const engEvidence = ctx.evidence.filter((e) => e.engagementId === engId);
  const engAuditFindings = ctx.auditFindings.filter((f) => f.engagementId === engId);
  const engPlans = ctx.auditPlans.filter((p) => p.engagementId === engId);
  const planIds = new Set(engPlans.map((p) => p.auditPlanId));
  const engProcedures = ctx.auditProcedures.filter((p) => planIds.has(p.auditPlanId));
  const procIds = new Set(engProcedures.map((p) => p.procedureId));
  const engSampling = ctx.samplingPlans.filter((s) => procIds.has(s.procedureId));
  const smpIds = new Set(engSampling.map((s) => s.samplingPlanId));
  const engSamples = ctx.sampleItems.filter((si) => smpIds.has(si.samplingPlanId));

  const traceResults = evaluateAllDisclosureTraceability({
    engagementId: engId,
    requirements: ctx.disclosureRequirements,
    mappings: ctx.disclosureMappings,
    assertions: engAssertions,
    controls: engControls,
    evidence: engEvidence,
    procedures: engProcedures,
    sampleItems: engSamples,
    designTests: engDesign,
    operatingTests: engOperating,
    emissionActivities: engActivities,
    ghgRecalculations: engRecalcs,
    auditFindings: engAuditFindings,
    calculationTimestamp: snapshot.generatedAt,
  });

  // 1. Executive Summary
  const execRows: Array<Array<string | number | boolean | null>> = [
    sanitizeExportRow(['Report ID', report.reportId]),
    sanitizeExportRow(['Frozen Snapshot ID', snapshot.snapshotId]),
    sanitizeExportRow(['Engagement ID', report.engagementId]),
    sanitizeExportRow(['Report Type', report.reportType]),
    sanitizeExportRow(['Reporting Period', report.reportingPeriod]),
    sanitizeExportRow(['Reporting Boundary', report.reportingBoundary]),
    sanitizeExportRow(['Methodology Version', report.methodologyVersion]),
    sanitizeExportRow(['Generated At', report.generatedAt]),
    sanitizeExportRow(['Generated By', report.generatedBy]),
    sanitizeExportRow(['Reviewed By', report.reviewedBy]),
    sanitizeExportRow(['Review Status', report.reviewStatus]),
    sanitizeExportRow(['Snapshot Hash (SHA-256)', snapshot.reportSnapshotHash]),
    sanitizeExportRow(['Mandatory Disclaimer', report.disclaimerStatement]),
    sanitizeExportRow([]),
    sanitizeExportRow(['Section ID', 'Section Title', 'Metric Label', 'Metric Value', 'Unit']),
  ];
  for (const sec of report.reportSections.filter((s) => s.included)) {
    for (const m of sec.keyMetrics) {
      execRows.push(
        sanitizeExportRow([sec.sectionId, sec.sectionTitle, m.label, m.value, m.unit ?? null])
      );
    }
  }
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(execRows, { cellDates: false }),
    'Executive Summary'
  );

  // 2. ESG Assertions (Preserves numeric values and null for Not Applicable/missing)
  const assertionRows: Array<Array<string | number | boolean | null>> = [
    sanitizeExportRow([
      'Assertion ID',
      'Engagement ID',
      'Facility ID',
      'Pillar',
      'Metric Code',
      'Metric Name',
      'Reporting Period',
      'Reported Value',
      'Value Basis',
      'Unit',
      'Data Source',
      'Calculation Method',
      'Review Status',
    ]),
    ...engAssertions.map((a) =>
      sanitizeExportRow([
        a.assertionId,
        a.engagementId,
        a.facilityId,
        a.pillar,
        a.metricCode,
        a.metricName,
        a.reportingYear,
        a.reportedValue,
        a.valueBasis,
        a.unit,
        a.dataSource,
        a.calculationMethod,
        a.reviewStatus,
      ])
    ),
  ];
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(assertionRows),
    'ESG Assertions'
  );

  // 3. Control Testing
  const controlRows: Array<Array<string | number | boolean | null>> = [
    sanitizeExportRow([
      'Test ID',
      'Test Type',
      'Control ID',
      'Testing Period',
      'Sample Size',
      'Exceptions',
      'Exceptions Evaluated',
      'Result / Conclusion',
      'Review Status',
      'Prepared By',
      'Reviewed By',
    ]),
    ...engDesign.map((d) =>
      sanitizeExportRow([
        d.designTestId,
        'Design Test',
        d.controlId,
        report.reportingPeriod,
        null,
        d.testResult === 'Design Deficiency' ? 1 : 0,
        true,
        d.testResult,
        d.reviewStatus,
        d.preparer,
        d.reviewer,
      ])
    ),
    ...engOperating.map((o) =>
      sanitizeExportRow([
        o.operatingTestId,
        'Operating Effectiveness Test',
        o.controlId,
        o.testingPeriod,
        o.sampleResults.length,
        o.exceptions,
        o.exceptionsEvaluated,
        o.conclusion,
        o.reviewStatus,
        o.preparer,
        o.reviewer,
      ])
    ),
  ];
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(controlRows),
    'Control Testing'
  );

  // 4. GHG Recalculations
  const ghgRows: Array<Array<string | number | boolean | null>> = [
    sanitizeExportRow([
      'Recalculation ID',
      'Activity ID',
      'Scope',
      'Activity Quantity',
      'Activity Unit',
      'Value Status',
      'Reported Emissions (tCO2e)',
      'Recalculated Emissions (tCO2e)',
      'Absolute Variance (tCO2e)',
      'Percentage Variance (%)',
      'Variance Status',
      'Methodology Version',
    ]),
    ...engActivities.map((act) => {
      const rec = engRecalcs.find((r) => r.activityId === act.activityId);
      return sanitizeExportRow([
        rec?.recalculationId ?? null,
        act.activityId,
        act.scope,
        act.activityQuantity,
        act.activityUnit,
        act.valueStatus,
        act.reportedEmissions,
        rec?.calculatedEmissions ?? null,
        rec?.absoluteVariance ?? null,
        rec?.percentageVariance ?? null,
        rec?.varianceStatus ?? 'Not Recalculated',
        rec?.methodologyVersion ?? null,
      ]);
    }),
  ];
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(ghgRows),
    'GHG Recalculations'
  );

  // 5. Disclosure Mapping
  const reqMap = new Map(ctx.disclosureRequirements.map((r) => [r.requirementId, r]));
  const mapRows: Array<Array<string | number | boolean | null>> = [
    sanitizeExportRow([
      'Mapping ID',
      'Requirement ID',
      'Framework ID',
      'Requirement Code',
      'Requirement Title',
      'Applicability Status',
      'Mapping Status',
      'CoveragePct (%)',
      'Traceability Status',
      'Linked Assertions',
      'Linked Controls',
      'Linked Tests',
      'Linked Evidence',
      'Linked Findings',
      'Missing Links',
    ]),
    ...traceResults.map((tr) => {
      const req = reqMap.get(tr.requirementId);
      const mp = ctx.disclosureMappings.find(
        (m) => m.engagementId === engId && m.requirementId === tr.requirementId
      );
      return sanitizeExportRow([
        mp?.mappingId ?? null,
        tr.requirementId,
        req?.frameworkId ?? null,
        req?.requirementCode ?? null,
        req?.requirementTitle ?? null,
        req?.applicabilityStatus ?? null,
        mp?.mappingStatus ?? 'Not Mapped',
        mp?.coveragePercentage ?? 0,
        tr.traceabilityStatus,
        tr.linkedAssertions.join('; '),
        tr.linkedControls.join('; '),
        tr.linkedTests.join('; '),
        tr.linkedEvidence.join('; '),
        tr.linkedFindings.join('; '),
        tr.missingLinks.join(' | '),
      ]);
    }),
  ];
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(mapRows),
    'Disclosure Mapping'
  );

  // 6. Evidence Register
  const evidenceRows: Array<Array<string | number | boolean | null>> = [
    sanitizeExportRow([
      'Evidence ID',
      'Engagement ID',
      'Document Name',
      'Evidence Type',
      'MIME Type',
      'File Size (Bytes)',
      'SHA-256 Checksum',
      'Linked Entity Type',
      'Linked Entity ID',
      'Verification Status',
      'Provenance Type',
      'Uploaded At',
    ]),
    ...engEvidence.map((e) =>
      sanitizeExportRow([
        e.evidenceId,
        e.engagementId,
        e.documentName,
        e.evidenceType,
        e.mimeType,
        e.fileSize,
        e.checksum,
        e.linkedEntityType,
        e.linkedEntityId,
        e.verificationStatus,
        e.isMetadataOnlyDemo ? 'Demo Metadata Only' : 'Uploaded Binary',
        e.uploadedAt,
      ])
    ),
  ];
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(evidenceRows),
    'Evidence Register'
  );

  // 7. Findings
  const findingRows: Array<Array<string | number | boolean | null>> = [
    sanitizeExportRow([
      'Finding ID',
      'Finding Type',
      'Severity',
      'Description',
      'Root Cause',
      'Impact',
      'Remediation Action',
      'Responsible Owner',
      'Target Date',
      'Remediation Status',
      'Retest Status',
    ]),
    ...engAuditFindings.map((f) =>
      sanitizeExportRow([
        f.auditFindingId,
        f.findingType,
        f.severity,
        f.description,
        f.rootCause,
        f.impact,
        f.remediationAction,
        f.responsibleOwner,
        f.targetDate,
        f.remediationStatus,
        f.retestStatus,
      ])
    ),
  ];
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(findingRows),
    'Findings'
  );

  // 8. Methodology
  const methodRows: Array<Array<string | number | boolean | null>> = [
    sanitizeExportRow(['Parameter', 'Value', 'Description']),
    sanitizeExportRow([
      'Report Engine Version',
      report.methodologyVersion,
      'Deterministic report builder and snapshot hash verification engine',
    ]),
    sanitizeExportRow([
      'Snapshot Hash Excluded Metadata',
      snapshot.excludedHashMetadataFields.join(', '),
      'Volatile metadata fields excluded from SHA-256 content hash for bit-for-bit reproducibility',
    ]),
    sanitizeExportRow([
      'Scope 2 Accounting Rule',
      'Separate Location-Based and Market-Based Totals',
      'Scope 2 Location-Based and Market-Based emissions are never summed into a single combined Scope 2 figure',
    ]),
    sanitizeExportRow([
      'Disclosure Coverage Denominator Rule',
      'Excludes Not Applicable Requirements',
      'Requirements designated Not Applicable are reported separately and excluded from applicable coverage denominators',
    ]),
    sanitizeExportRow([
      'Impact Materiality Likelihood Rule',
      'Actual Impacts = null Likelihood',
      'Actual impacts are evaluated on Severity (Scale, Scope, Irremediability) without applying a likelihood multiplier',
    ]),
    sanitizeExportRow([
      'Mandatory Non-Opinion Disclaimer',
      report.disclaimerStatement,
      'Required internal assurance-readiness disclaimer',
    ]),
  ];
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(methodRows),
    'Methodology'
  );

  const out = XLSX.write(wb, { type: 'array', bookType: 'xlsx' }) as ArrayBuffer;
  return new Uint8Array(out);
}

/**
 * Helper to parse XLSX bytes back into a workbook for automated verification tests.
 */
export function readXlsxWorkbookFromBytes(bytes: Uint8Array): XLSX.WorkBook {
  return XLSX.read(bytes, { type: 'array' });
}

function escapeCsvCell(val: string | number | boolean | null): string {
  if (val === null || val === undefined) {
    return '';
  }
  if (typeof val === 'number' || typeof val === 'boolean') {
    return String(val);
  }
  const safeStr = String(sanitizeSpreadsheetValue(val) ?? '');
  if (
    safeStr.includes(',') ||
    safeStr.includes('"') ||
    safeStr.includes('\n') ||
    safeStr.includes('\r')
  ) {
    return `"${safeStr.replace(/"/g, '""')}"`;
  }
  return safeStr;
}

/**
 * 8.3 CSV Export Engine
 * Exports deterministic, formula-injection-protected CSVs for:
 * - disclosure-mappings
 * - testing-results
 * - findings
 * - ghg-recalculations
 */
export function generateModuleCsvExport(
  category: CsvExportCategory,
  snapshot: FrozenReportSnapshot,
  ctx: ReportGenerationContext
): string {
  const engId = snapshot.engagementId;
  const rows: Array<Array<string | number | boolean | null>> = [];

  if (category === 'disclosure-mappings') {
    rows.push([
      'snapshotId',
      'engagementId',
      'mappingId',
      'requirementId',
      'frameworkId',
      'requirementCode',
      'applicabilityStatus',
      'mappingStatus',
      'coveragePercentage',
      'linkedAssertionIds',
      'linkedControlIds',
      'linkedProcedureIds',
      'linkedEvidenceIds',
      'reviewedBy',
    ]);
    const reqMap = new Map(ctx.disclosureRequirements.map((r) => [r.requirementId, r]));
    const mappings = ctx.disclosureMappings
      .filter((m) => m.engagementId === engId)
      .sort((a, b) => a.mappingId.localeCompare(b.mappingId));
    for (const m of mappings) {
      const req = reqMap.get(m.requirementId);
      rows.push(
        sanitizeExportRow([
          snapshot.snapshotId,
          m.engagementId,
          m.mappingId,
          m.requirementId,
          m.frameworkId,
          req?.requirementCode ?? null,
          req?.applicabilityStatus ?? null,
          m.mappingStatus,
          m.coveragePercentage,
          m.linkedAssertionIds.join(';'),
          m.linkedControlIds.join(';'),
          m.linkedProcedureIds.join(';'),
          m.linkedEvidenceIds.join(';'),
          m.reviewedBy,
        ])
      );
    }
  } else if (category === 'testing-results') {
    rows.push([
      'snapshotId',
      'engagementId',
      'operatingTestId',
      'controlId',
      'testingPeriod',
      'sampleSize',
      'exceptions',
      'exceptionsEvaluated',
      'conclusion',
      'reviewStatus',
      'preparer',
      'reviewer',
    ]);
    const ctrlIds = new Set(
      ctx.controls.filter((c) => c.engagementId === engId).map((c) => c.controlId)
    );
    const opTests = ctx.operatingTests
      .filter((o) => ctrlIds.has(o.controlId))
      .sort((a, b) => a.operatingTestId.localeCompare(b.operatingTestId));
    for (const o of opTests) {
      rows.push(
        sanitizeExportRow([
          snapshot.snapshotId,
          engId,
          o.operatingTestId,
          o.controlId,
          o.testingPeriod,
          o.sampleResults.length,
          o.exceptions,
          o.exceptionsEvaluated,
          o.conclusion,
          o.reviewStatus,
          o.preparer,
          o.reviewer,
        ])
      );
    }
  } else if (category === 'findings') {
    rows.push([
      'snapshotId',
      'engagementId',
      'auditFindingId',
      'findingType',
      'severity',
      'description',
      'rootCause',
      'impact',
      'remediationAction',
      'responsibleOwner',
      'targetDate',
      'remediationStatus',
      'retestStatus',
    ]);
    const findings = ctx.auditFindings
      .filter((f) => f.engagementId === engId)
      .sort((a, b) => a.auditFindingId.localeCompare(b.auditFindingId));
    for (const f of findings) {
      rows.push(
        sanitizeExportRow([
          snapshot.snapshotId,
          f.engagementId,
          f.auditFindingId,
          f.findingType,
          f.severity,
          f.description,
          f.rootCause,
          f.impact,
          f.remediationAction,
          f.responsibleOwner,
          f.targetDate,
          f.remediationStatus,
          f.retestStatus,
        ])
      );
    }
  } else {
    rows.push([
      'snapshotId',
      'engagementId',
      'recalculationId',
      'activityId',
      'scope',
      'activityQuantity',
      'activityUnit',
      'valueStatus',
      'reportedEmissions',
      'calculatedEmissions',
      'absoluteVariance',
      'percentageVariance',
      'varianceStatus',
    ]);
    const acts = ctx.emissionActivities
      .filter((a) => a.engagementId === engId)
      .sort((a, b) => a.activityId.localeCompare(b.activityId));
    for (const a of acts) {
      const r = ctx.ghgRecalculations.find((rec) => rec.activityId === a.activityId);
      rows.push(
        sanitizeExportRow([
          snapshot.snapshotId,
          engId,
          r?.recalculationId ?? null,
          a.activityId,
          a.scope,
          a.activityQuantity,
          a.activityUnit,
          a.valueStatus,
          a.reportedEmissions,
          r?.calculatedEmissions ?? null,
          r?.absoluteVariance ?? null,
          r?.percentageVariance ?? null,
          r?.varianceStatus ?? 'Not Recalculated',
        ])
      );
    }
  }

  return rows.map((r) => r.map(escapeCsvCell).join(',')).join('\n');
}

/**
 * 8.4 Structured JSON Export Engine
 * Produces a schema-validated JSON export from the frozen report snapshot.
 */
export function generateStructuredJsonExport(snapshot: FrozenReportSnapshot): string {
  const payload = {
    schemaVersion: 'v0.3.0' as const,
    exportedAt: snapshot.generatedAt,
    snapshotId: snapshot.snapshotId,
    reportId: snapshot.reportId,
    engagementId: snapshot.engagementId,
    reportType: snapshot.reportType,
    reportingPeriod: snapshot.reportingPeriod,
    methodologyVersion: snapshot.reportData.methodologyVersion,
    disclaimerStatement: snapshot.reportData.disclaimerStatement,
    reportSnapshotHash: snapshot.reportSnapshotHash,
    excludedHashMetadataFields: snapshot.excludedHashMetadataFields,
    sourceRecordIds: snapshot.reportData.sourceRecordIds,
    reportSections: snapshot.reportData.reportSections,
  };

  const validated = StructuredJsonExportSchema.parse(payload);
  return JSON.stringify(validated, null, 2);
}

/**
 * Triggers a safe browser download of binary or text export data.
 */
export function triggerBrowserDownload(params: {
  filename: string;
  extension: 'pdf' | 'xlsx' | 'csv' | 'json';
  content: Uint8Array | string;
  mimeType: string;
}): string {
  const safeFilename = sanitizeExportFilename(params.filename, params.extension);
  if (typeof window === 'undefined' || typeof document === 'undefined' || typeof Blob === 'undefined') {
    return safeFilename;
  }

  const blob =
    typeof params.content === 'string'
      ? new Blob([params.content], { type: params.mimeType })
      : new Blob([params.content.buffer as ArrayBuffer], { type: params.mimeType });

  if (typeof URL !== 'undefined' && typeof URL.createObjectURL === 'function') {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = safeFilename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    setTimeout(() => URL.revokeObjectURL(url), 1500);
  }
  return safeFilename;
}
